#pragma once

#include "cores/DllLoader/LibraryLoader.h"

#include <string>

/*!
 * \brief Entry points of a binary add-on that is linked into the executable.
 *
 * A browser cannot load a shared library at run time, so the add-ons named by
 * the WASM_STATIC_ADDONS build option are linked in and listed in a table that
 * the build generates.
 */
struct StaticAddonLibrary
{
  const char* fileName; // as named by the add-on's addon.xml
  void* create;
  void* getTypeVersion;
  void* getTypeMinVersion;
};

// Generated by cmake/scripts/wasm/ExtraTargets.cmake; ends with an entry without a name.
extern const StaticAddonLibrary g_staticAddonLibraries[];

/*!
 * \brief Stands in for a shared library whose code is part of the executable.
 */
class CStaticAddonLoader : public LibraryLoader
{
public:
  explicit CStaticAddonLoader(const std::string& libraryFile);

  bool Load() override;
  void Unload() override;
  int ResolveExport(const char* symbol, void** ptr, bool logging = true) override;
  bool IsSystemDll() override { return false; }
  HMODULE GetHModule() override { return nullptr; }
  bool HasSymbols() override { return false; }

private:
  const StaticAddonLibrary* m_library{nullptr};
};
